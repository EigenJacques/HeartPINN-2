    def single_import(self, path:str="", scaling_l:float=1.0):
        """ Imports a single collocation dataset, generated by freecad. """

        X_fluid, X_in, X_out, X_wall, X_symmetry, N_wall, N_symmetry = load(open(path, 'rb'))

        X_fluid     = tf.convert_to_tensor(X_fluid/scaling_l, dtype=self.prec)
        X_in        = tf.convert_to_tensor(X_in/scaling_l, dtype=self.prec)
        X_out       = tf.convert_to_tensor(X_out/scaling_l, dtype=self.prec)
        X_wall      = tf.convert_to_tensor(X_wall/scaling_l, dtype=self.prec)
        X_symmetry  = tf.convert_to_tensor(X_symmetry/scaling_l, dtype=self.prec)

        self.N_wall     = tf.convert_to_tensor(N_wall, dtype=self.prec)
        self.N_symmetry = tf.convert_to_tensor(N_symmetry, dtype=self.prec)

        standard_collocation = [X_fluid, X_in, X_out, X_wall, X_symmetry]
        standard_normals     = [N_wall, N_symmetry]
        return standard_collocation, standard_normals
    
    def mesh(self, X, n=10, inverse_distance=True):
        """ Create the connectivity matrix for graph convolutional neural networks .     
        """ 

        adiv = 1000

        A = NearestNeighbors(n_neighbors=n, algorithm="brute").fit(X).kneighbors_graph(X, mode="distance").toarray()

        A_hat = A
        amax = np.max(A)
        if inverse_distance == False:
            for i, x in enumerate(A_hat):
                for j, y in enumerate(x):
                    if y != 0.0:
                        A_hat[i, j] = amax - A_hat[i, j]
        
        D = np.sum(A_hat, axis=0)
        A_hat = A_hat/np.max(A_hat)/adiv
        A_hat = A_hat + np.diag(np.ones(A_hat.shape[0]))

        assert np.sum(A_hat - A_hat.T) < 1E-6, f"Adjacency matrix not symmetric with error{np.sum(A_hat - A_hat.T)}"

        return A, D, tf.sparse.from_dense(tf.convert_to_tensor(A_hat, dtype=self.prec))

    def condition(self, X, T_in, Y_in):
        """ Perform conditioning on a field to improve numerical performance . 
            Operations performed:
                - Remove nans
                - Remove outliers
                - Smooth non smooth data
            
            Arguments
            ----------
            X : tf.Tensor
                Coordinates of collocation points
            
            T_in : list
                List of tensors to check for nans and outliers

            Y_in : list
                List of tensors to apply the same operations to as T_in

            args: dict
                Dictionary of hyperparamters for the conditioning operations.
        """ 

        def id_nans(T, I_err):
            """Appends the boolean mask of entries that have nans in any of the columns of T to I_err"""

            I     = tf.expand_dims(tf.reduce_any(tf.where(tf.math.is_nan(T), tf.zeros_like(T, dtype=tf.bool),
                                                          tf.ones_like(T, dtype=tf.bool)), axis=1), axis=1)
            I_err = tf.concat([I_err,I],axis=1)
            
            return I_err
        
        def id_outliers(T, I_err):
            """Appends the boolean mask of entries that are outliers in any of the columns of T to I_err"""

            for d in range(T.shape[1]):
                # find outliers
                T_mean = tf.math.reduce_mean(T[:,d])
                T_std = tf.math.reduce_std(T[:,d])
                I_outlier = tf.where(tf.math.logical_or(T[:,d] > T_mean + self.condargs["sigma"]*T_std, T[:,d] < T_mean - self.condargs["sigma"]*T_std),
                                    tf.zeros_like(T[:,d], dtype=tf.bool), tf.ones_like(T[:,d], dtype=tf.bool))
                I_outlier = tf.expand_dims(I_outlier, axis=1)
                I_err = tf.concat([I_err,I_outlier],axis=1)

            return I_err
        
        def id_smooth(X, T, I_err):
            """Appends the boolean mask of entries that are outliers in any of the columns of T to I_err"""

            threshold = self.condargs["threshold"]*self.scaling_l

            for d in range(T.shape[1]):
                # find outliers

                rbf = RBFInterpolator(X.numpy(), T[:,d].numpy(), smoothing=self.condargs["smoothing"])(X.numpy())

                I_outlier = tf.where(tf.convert_to_tensor(np.abs(rbf - T[:,d].numpy()), dtype=self.prec) > threshold,
                                      tf.zeros_like(T[:,d], dtype=tf.bool), tf.ones_like(T[:,d], dtype=tf.bool))
                I_outlier = tf.expand_dims(I_outlier, axis=1)
                I_err = tf.concat([I_err,I_outlier],axis=1)

            return I_err
        
        T_out = []
        Y_out = []
        X = X[0]

        # Remove nan entries
        I_err = tf.Variable(tf.ones_like(T_in[0][:,0:1], dtype=tf.bool))
        for T in T_in:
            I_err = id_nans(T, I_err)
        I_err = tf.reduce_all(I_err, axis=1)

        for i, T in enumerate(T_in):
            T_in[i] =  tf.boolean_mask(T, I_err)

        for i, Y in enumerate(Y_in):
            Y_in[i] =  tf.boolean_mask(Y, I_err)

        X = tf.boolean_mask(X, I_err)

        # # Remove statistical outliers
        # I_err = tf.Variable(tf.ones_like(T_in[0][:,0:1], dtype=tf.bool))
        # for T in T_in:
        #     I_err = id_outliers(T, I_err)
        # I_err = tf.reduce_all(I_err, axis=1)

        # for i, T in enumerate(T_in):
        #     T_in[i] =  tf.boolean_mask(T, I_err)

        # for i, Y in enumerate(Y_in):
        #     Y_in[i] =  tf.boolean_mask(Y, I_err)

        # X = tf.boolean_mask(X, I_err)

        # Remove smoothness outliers
        I_err = tf.Variable(tf.ones_like(T_in[0][:,0:1], dtype=tf.bool))
        for T in T_in:
            I_err = id_smooth(X, T, I_err)
        I_err = tf.reduce_all(I_err, axis=1)


        for i, T in enumerate(T_in):
            T_in[i] =  tf.boolean_mask(T, I_err)

        for i, Y in enumerate(Y_in):
            Y_in[i] =  tf.boolean_mask(Y, I_err)

        X = tf.boolean_mask(X, I_err)

        T_out = T_in
        Y_out = Y_in
        X_out = X

        return X_out, T_out, Y_out

    def rect_coll(self, ncol):
        """ Returns a tensor of ncol points in a rectangle of width w and height h. """

        X_fluid         = stats.qmc.Sobol(2, seed = 10).random_base2(ncol[0])
        X_fluid[:,0]    = X_fluid[:,0]*self.w ; X_fluid[:,1] = X_fluid[:,1]*self.h
        X_fluid         = tf.convert_to_tensor(X_fluid, dtype=self.prec)

        X_wall                              = stats.qmc.Sobol(2, seed = 10)
        X_wall                              = X_wall.random_base2(ncol[1])
        X_wall[0:int(X_wall.shape[0]/2), 1] = X_wall[0:int(X_wall.shape[0]/2), 1]*0
        X_wall[int(X_wall.shape[0]/2)::, 1] = np.ones(int(X_wall.shape[0]/2))*self.h
        X_wall[:, 0]                        = X_wall[:, 0]*self.w
        X_wall                              = tf.convert_to_tensor(X_wall, dtype=self.prec)

        X_in = np.hstack((0*np.ones(2**ncol[2])[: , np.newaxis],
                          self.h*stats.qmc.Sobol(1, seed = 10).random_base2(ncol[2])))
        X_in = tf.convert_to_tensor(X_in, dtype=self.prec)

        X_out   = np.hstack((self.w*np.ones(2**ncol[3])[: , np.newaxis],
                             self.h*stats.qmc.Sobol(1, seed = 10).random_base2(ncol[3])))
        X_out   = tf.convert_to_tensor(X_out, dtype=self.prec)

        # Scaling:
        X_fluid = X_fluid/self.scaling_l
        X_wall  = X_wall/self.scaling_l
        X_in    = X_in/self.scaling_l
        X_out   = X_out/self.scaling_l

        return X_fluid, X_in, X_out, X_wall
    
