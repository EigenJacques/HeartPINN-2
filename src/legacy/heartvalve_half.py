        self.standard_normals     = self.single_import(self.collocationpaths[0], self.scaling_l)[1]

        if len(self.collocationpaths) > 1:
            self.dense_collocation    = self.single_import(self.collocationpaths[1], self.scaling_l)[0]
            self.med_collocation      = self.single_import(self.collocationpaths[2])[0]
