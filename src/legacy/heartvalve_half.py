    def rect_floaters_bound(self, X_fluid:tf.Tensor, w:float, h:float, scaling_l:float):
        """ Return distances from all boundary conditions using floaters mean value coordinates. """

        h, w = h/scaling_l, w/scaling_l

        # Vertices for Xf_bound
        Xf_bound = np.array([[0,0]])
        Xf_bound = np.vstack((Xf_bound, np.array([[0,h]])))
        Xf_bound = np.vstack((Xf_bound, np.array([[w,h]])))
        Xf_bound = np.vstack((Xf_bound, np.array([[w,0]])))
