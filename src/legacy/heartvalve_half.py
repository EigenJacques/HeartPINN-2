    def rect_floaters_hard(self, X_fluid:tf.Tensor, w:float, h:float,
                            inletfatness:float, conditioner, scaling_l:float, carryalong:list, do_condition:bool):
        """ Returns all the spacial fields required to enforce hard constraints, using floaters mean value  coordinates. """

        h, w = h/scaling_l, w/scaling_l

        def fat_inlet(walldist, inletfatness):

            bounddist1      = X_fluid[:,0:1]
            bounddist2      = -X_fluid[:,0:1] + inletfatness/scaling_l
            zero_function   = tf.zeros_like(walldist)
            power           = 2
            walldist        = tf.math.minimum(bounddist2**power*zero_function + 
                                              bounddist1**power*walldist/(bounddist1**power + bounddist2**power),
                                              walldist)
            return walldist

        # Vertices for Xf_out
        Xf_out = np.array([[-100/scaling_l,-100/scaling_l]])
        Xf_out = np.vstack((Xf_out, np.array([[-100/scaling_l,100/scaling_l]])))
        Xf_out = np.vstack((Xf_out, np.array([[w,100/scaling_l]])))
        Xf_out = np.vstack((Xf_out, np.array([[w, -100/scaling_l]])))
        Xf_out = np.flip(Xf_out, axis=0)
        Xf_out = tf.convert_to_tensor(Xf_out, dtype=self.prec)

        # Vertices for Xf_in
        Xf_in = np.array([[0,-50/scaling_l]])
        Xf_in = np.vstack((Xf_in, np.array([[0,50/scaling_l]])))
        Xf_in = np.vstack((Xf_in, np.array([[200/scaling_l,50/scaling_l]])))
        Xf_in = np.vstack((Xf_in, np.array([[200/scaling_l,-50/scaling_l]])))
        Xf_in = np.flip(Xf_in, axis=0)
        Xf_in = tf.convert_to_tensor(Xf_in, dtype=self.prec)

        # Vertices for Xf_wall
        Xf_wall = np.array([[-10/scaling_l,0]])
        Xf_wall = np.vstack((Xf_wall, np.array([[-10/scaling_l,h]])))
        Xf_wall = np.vstack((Xf_wall, np.array([[100/scaling_l,h]])))
        Xf_wall = np.vstack((Xf_wall, np.array([[100/scaling_l,0]])))
        Xf_wall = np.flip(Xf_wall, axis=0)
        Xf_wall = tf.convert_to_tensor(Xf_wall, dtype=self.prec)

        # # Calculate Fp, Fu, Fv
        with tf.GradientTape(persistent=True) as tape:
            tape.watch(X_fluid)

            F_in    = fat_inlet(-self.Fl(Xf_in,X_fluid), inletfatness)
            F_out   = -self.Fl(Xf_out,X_fluid)
            F_wall  = -self.Fl(Xf_wall,X_fluid)

            n  = 4

            w_in    =   (F_wall*F_out)/(F_out*F_wall + F_in*F_wall + F_in*F_out)
            w_out   =   (F_in*F_wall)/(F_out*F_wall + F_in*F_wall + F_in*F_out)

            w_wall  =   (F_in*F_out)/(F_out*F_wall + F_in*F_wall + F_in*F_out)

        dF_in   = tape.gradient(F_in, X_fluid)
        dF_out  = tape.gradient(F_out, X_fluid)
        dF_wall = tape.gradient(F_wall, X_fluid)
        dw_in   = tape.gradient(w_in, X_fluid)
        dw_out  = tape.gradient(w_out, X_fluid)
        dw_wall = tape.gradient(w_wall, X_fluid)
        del tape

        if do_condition:
            X_fluid, [F_in, F_out, F_wall, dF_in, dF_out, dF_wall,
                    w_in, w_out, w_wall, dw_in, dw_out, dw_wall], carryalong = conditioner([X_fluid],[F_in, F_out, F_wall, dF_in, dF_out, dF_wall, w_in, w_out, w_wall, dw_in, dw_out, dw_wall], carryalong)

        return X_fluid, [F_in, F_out, F_wall, dF_in, dF_out, dF_wall, w_in, w_out, w_wall, dw_in, dw_out, dw_wall], carryalong

