        Xf_wall = np.vstack((Xf_wall, np.array([[100/scaling_l,h]])))
        Xf_wall = np.vstack((Xf_wall, np.array([[100/scaling_l,0]])))
        Xf_wall = np.flip(Xf_wall, axis=0)
        Xf_wall = tf.convert_to_tensor(Xf_wall, dtype=self.prec)

        F_wall     = -self.Fl(Xf_wall,X_fluid)

